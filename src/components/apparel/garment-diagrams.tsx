export function GarmentDiagram({ type, side, fillColor }: GarmentDiagramProps) {
  const cfg = PATHS[type] || PATHS.tshirt;
  const dPaths = side === 'side' ? (cfg.side || cfg.front) : side === 'front' ? cfg.front : (cfg.back || cfg.front);
  const fillPath = FILL_PATHS[type] || FILL_PATHS.tshirt;
  return (
    <svg
      viewBox={cfg.viewBox}
      fill="none"
      stroke="#71717A"
      strokeWidth={type === 'cap' ? 1 : 1.2}
      strokeLinecap="round"
      strokeLinejoin="round"
      xmlns="http://www.w3.org/2000/svg"
      className="w-full h-full opacity-80"
      aria-hidden="true"
    >
      {fillColor && (
        <path d={fillPath} fill={fillColor} stroke="none" className="transition-colors duration-300" />
      )}
      {dPaths.map((d, i) => (
        <path key={i} d={d} />
      ))}
      {type === 'cap' && (
        <circle cx="32" cy="14" r="2.5" fill="#71717A" stroke="none" />
      )}
      {type === 'hoodie-hood' && side === 'front' && (
        <>
          <circle cx="72" cy="56" r="1.5" fill="#71717A" stroke="none" />
          <circle cx="128" cy="56" r="1.5" fill="#71717A" stroke="none" />
        </>
      )}
      {type === 'jacket-hood' && side === 'front' && (
        <>
          <circle cx="70" cy="51" r="1.5" fill="#71717A" stroke="none" />
          <circle cx="130" cy="51" r="1.5" fill="#71717A" stroke="none" />
        </>
      )}
      {type === 'polo' && side === 'front' && (
        <>
          <circle cx="100" cy="74" r="2" fill="#71717A" stroke="none" />
          <circle cx="100" cy="84" r="2" fill="#71717A" stroke="none" />
        </>
      )}
    </svg>
  );
}